def test_service_logs_filters_are_documented_as_literal(schema: dict) -> None:
    """``grep`` is a substring, and the schema an agent reads must say so (WP3.2).

    The bug class this pins: an agent reads "grep", assumes a regex, sends
    ``Traceback.*Error``, gets zero rows back, and concludes the service logged
    nothing. Both the paged read and the stream must carry the same wording.
    """
    for path in ("/api/services/{ident}/logs", "/api/services/{ident}/logs/stream"):
        params = {
            p["name"]: p.get("description", "").lower()
            for p in schema["paths"][path]["get"]["parameters"]
        }
        assert "not a regex" in params["grep"], path
        assert "iso-8601" in params["since"], path


