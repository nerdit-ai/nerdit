def test_p26_operation_ids_are_present(schema: dict) -> None:
    """The P26 WP-H exposure surface keeps its pinned operationIds.

    Three share operations under the new ``Exposure`` tag plus ``refresh_link``,
    which stays on the existing ``Link`` tag — it is a link-custody op (it
    commits ``[link]`` config under the same admin gate and mutation lock as the
    claim), not an exposure one, and a generated client should find it beside
    ``claim_link``.
    """
    op_ids = {op.get("operationId") for _, _, op in _operations(schema)}
    expected = {
        "get_share",
        "set_share",
        "remove_share",
        "refresh_link",
        "list_domains",
        "add_domain",
        "remove_domain",
    }
    missing = expected - op_ids
    assert not missing, f"P26 operationIds missing from the schema: {sorted(missing)}"

    paths = schema["paths"]
    share_ops = paths["/api/services/{name}/share"]
    assert set(share_ops) == {"get", "put", "delete"}
    # The share trio is Exposure; refresh is Link. Getting this backwards would
    # scatter the surface across two headings in every generated client.
    for method in ("get", "put", "delete"):
        assert share_ops[method]["tags"] == ["Exposure"]
    assert paths["/api/link/refresh"]["post"]["tags"] == ["Link"]
    # ``/api`` only, like the link and workspace surfaces — no bare-root alias.
    assert "/services/{name}/share" not in paths
    assert "/link/refresh" not in paths


def test_p26_wp1_domain_operations_are_present(schema: dict) -> None:
    """(P26 WP1) The custom-domain trio joins the SAME ``Exposure`` tag.

    Split across two paths on purpose (S-W2): the domain is the resource id, so
    the collection lists and the item is bound/released. Both are ``/api``-only,
    like the share trio they sit beside.
    """
    paths = schema["paths"]
    collection = paths["/api/services/{name}/domains"]
    item = paths["/api/services/{name}/domains/{domain}"]
    assert set(collection) == {"get"}
    assert set(item) == {"put", "delete"}
    assert collection["get"]["operationId"] == "list_domains"
    assert item["put"]["operationId"] == "add_domain"
    assert item["delete"]["operationId"] == "remove_domain"
    for op in (collection["get"], item["put"], item["delete"]):
        assert op["tags"] == ["Exposure"]
    assert "/services/{name}/domains" not in paths
    assert "/services/{name}/domains/{domain}" not in paths


