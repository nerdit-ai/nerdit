"""OpenAPI curation drift guard (P6 / D4).

Asserts the schema stays agent-consumable: every documented operation carries a
tag and a stable, explicit, unique ``operationId`` (generated clients pin to
these ids — a rename or a fallback to FastAPI's autogenerated
``handlername_path_method`` id is a breaking change).

``app.openapi()`` is sync, so no TestClient (and no aiosqlite lifespan) is
needed here.
"""

