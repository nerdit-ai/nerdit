def test_list_events_documents_both_pagination_directions(schema: dict) -> None:
    """The two modes are a contract, not an implementation detail (WP2.1).

    The bug class this pins: a consumer told to "reconcile" reaches for
    ``cursor``, which walks **backwards** into history, and silently never sees
    the events it was reconciling toward. The direction of each param must be
    stated in the schema an agent reads.
    """
    params = schema["paths"]["/api/events"]["get"]["parameters"]
    described = {p["name"]: p.get("description", "").lower() for p in params}
    assert "cursor browses backwards, id desc" in described["cursor"]
    assert "since_id replays forwards, id asc" in described["since_id"]


